local function settings(over) local s = { style="grid", iconSize=40, spacing=6, direction="RIGHT", perRow=8, showNames=false, alertStyle="flash", highScale=1.15, lowScale=0.7, revision=1, position={point="CENTER", x=0, y=180} }; for k,v in pairs(over or {}) do s[k]=v end; return s end
local function fakeState(tracked, status, stale, prio)
  local s = { tracked=tracked, status=status, stale=stale or false, prio=prio or {} }
  function s:Priority(k) return self.prio[k] or "normal" end
  function s:TrackedKeys() local r = {}; for _, e in ipairs(FB.Data.entries) do if tracked[e.key] then r[#r+1] = e.key end end; return r end
  function s:Missing() local r = {}; for _, k in ipairs(self:TrackedKeys()) do if status[k] == "missing" then r[#r+1] = k end end; return r end
  function s:IconSpell(k) return FB.Data.byKey[k].iconSpells[#FB.Data.byKey[k].iconSpells] end
  function s:Recommendation(k) return s.rec and s.rec[k] or nil end
  return s
end
local function shownIcons()
  local shown, n = {}, 0
  for _, ic in ipairs(FB.Display.icons) do if ic:IsShown() then shown[ic.key] = ic; n = n + 1 end end
  return shown, n
end
