local H = dofile("tests/helpers.lua")
local env = H.env

T.test("self buff tracked only when known", function()
  local s = FB.State.New(FB.Data, env({ known={} })); s:ComputeTracked(); T.falsy(s.tracked.inner_fire)
  s = FB.State.New(FB.Data, env({ known={[588]=true} })); s:ComputeTracked(); T.eq(s.tracked.inner_fire.reason, "known")
end)
T.test("level-1 character with no group tracks nothing", function()
  local s = FB.State.New(FB.Data, env({ level=1 })); s:ComputeTracked(); T.eq(next(s.tracked), nil)
end)
T.test("group buff tracked by eligible member class and level", function()
  local s = FB.State.New(FB.Data, env({ group={{class="PRIEST", level=29}} })); s:ComputeTracked()
  T.eq(s.tracked.fortitude.reason, "group"); T.falsy(s.tracked.divine_spirit)
  s = FB.State.New(FB.Data, env({ group={{class="PRIEST", level=30}} })); s:ComputeTracked(); T.truthy(s.tracked.divine_spirit)
end)
T.test("unknown member level 0 or -1 counts as eligible", function()
  for _, lvl in ipairs({0, -1}) do
    local s = FB.State.New(FB.Data, env({ group={{class="PRIEST", level=lvl}} })); s:ComputeTracked(); T.truthy(s.tracked.divine_spirit)
  end
end)
T.test("selfOnly entries never tracked via group", function()
  local s = FB.State.New(FB.Data, env({ group={{class="PRIEST", level=60}} })); s:ComputeTracked(); T.falsy(s.tracked.inner_fire)
end)
T.test("priority defaults by reason and can be overridden", function()
  local s = FB.State.New(FB.Data, env({ known={[6673]=true}, group={{class="WARRIOR", level=10}} })); s:ComputeTracked(); T.eq(s:Priority("battle_shout"), "normal")
  s = FB.State.New(FB.Data, env({ group={{class="WARRIOR", level=10}} })); s:ComputeTracked(); T.eq(s:Priority("battle_shout"), "low")
  s = FB.State.New(FB.Data, env({ instance="raid" })); s:ComputeTracked(); T.eq(s:Priority("flask"), "low")
  s = FB.State.New(FB.Data, env({ group={{class="PRIEST", level=10}}, settings={ priority={ fortitude="high" } } })); s:ComputeTracked(); T.eq(s:Priority("fortitude"), "high")
  T.eq(s:Priority("inner_fire"), "normal"); T.eq(s.tracked.battle_shout, nil)
end)
T.test("pick overrides recommendation, even above the player's level", function()
  local s = FB.State.New(FB.Data, env({ class="MAGE", level=30, settings={ pick={ weapon=20749 } } }))
  local r = s:Recommendation("weapon_mh"); T.eq(r.itemID, 20749); T.truthy(r.picked); T.eq(r.name, "Brilliant Wizard Oil")
  T.eq(s:Recommendation("weapon_oh").itemID, 20749)
  s = FB.State.New(FB.Data, env({ class="MAGE", level=60, settings={ pick={ elixir=999999 } } })); T.eq(s:Recommendation("elixir").itemID, 21546); T.falsy(s:Recommendation("elixir").picked)
end)
T.test("disabled entries and default-off entries", function()
  local s = FB.State.New(FB.Data, env({ known={[588]=true}, enabled={inner_fire=false} })); s:ComputeTracked(); T.falsy(s.tracked.inner_fire)
  s = FB.State.New(FB.Data, env({ group={{class="PRIEST", level=60}} })); s:ComputeTracked(); T.falsy(s.tracked.shadow_protection)
  s = FB.State.New(FB.Data, env({ group={{class="PRIEST", level=60}}, enabled={shadow_protection=true} })); s:ComputeTracked(); T.truthy(s.tracked.shadow_protection)
end)
T.test("rogue off-hand poison requires an off-hand weapon", function()
  local o = { known={[8681]=true}, offhandWeapon=false }
  local s = FB.State.New(FB.Data, env(o)); s:ComputeTracked(); T.truthy(s.tracked.rogue_poison_mh); T.falsy(s.tracked.rogue_poison_oh)
  o.offhandWeapon = true; s:ComputeTracked(); T.truthy(s.tracked.rogue_poison_oh)
end)
T.test("consumable scopes per category, remind on drop, never in battlegrounds", function()
  local s = FB.State.New(FB.Data, env({ instance="none" })); s:ComputeTracked(); T.falsy(s.tracked.elixir); T.falsy(s.tracked.flask)
  s = FB.State.New(FB.Data, env({ instance="party" })); s:ComputeTracked(); T.truthy(s.tracked.elixir); T.falsy(s.tracked.flask)
  s = FB.State.New(FB.Data, env({ instance="raid" })); s:ComputeTracked(); T.eq(s.tracked.flask.reason, "consumable"); T.truthy(s.tracked.elixir)
  s = FB.State.New(FB.Data, env({ instance="none", settings={ consumableWhere={ elixir="everywhere" } } })); s:ComputeTracked(); T.truthy(s.tracked.elixir)
  s = FB.State.New(FB.Data, env({ instance="none" })); s.seenConsumable.flask = true; s:ComputeTracked(); T.truthy(s.tracked.flask)
  s = FB.State.New(FB.Data, env({ instance="none", settings={ consumablesRemindDrop=false } })); s.seenConsumable.flask = true; s:ComputeTracked(); T.falsy(s.tracked.flask)
  s = FB.State.New(FB.Data, env({ instance="none", settings={ consumableWhere={ flask="never" } } })); s.seenConsumable.flask = true; s:ComputeTracked(); T.falsy(s.tracked.flask)
  s = FB.State.New(FB.Data, env({ instance="raid", settings={ consumableWhere={ weapon="never" } } })); s:ComputeTracked(); T.falsy(s.tracked.weapon_mh)
  s = FB.State.New(FB.Data, env({ instance="pvp", settings={ consumableWhere={ flask="everywhere" } } })); s.seenConsumable.flask = true; s:ComputeTracked(); T.falsy(s.tracked.flask)
end)
T.test("Shows and Sounds defaults and overrides", function()
  local s = FB.State.New(FB.Data, env({ known={[588]=true}, group={{class="MAGE", level=10}}, instance="raid" })); s:ComputeTracked()
  T.truthy(s:Shows("inner_fire")); T.truthy(s:Sounds("inner_fire"))
  T.truthy(s:Shows("arcane_intellect")); T.falsy(s:Sounds("arcane_intellect"))
  T.falsy(s:Shows("righteous_fury")); T.falsy(s:Sounds("righteous_fury"))
  T.truthy(s:Shows("flask")); T.falsy(s:Sounds("flask"))
  s = FB.State.New(FB.Data, env({ instance="raid", settings={ sound={ flask=true } } })); T.truthy(s:Sounds("flask"))
end)
T.test("show off and sound on still tracks; both off untracks", function()
  local s = FB.State.New(FB.Data, env({ known={[588]=true}, settings={ show={ inner_fire=false } } })); s:ComputeTracked(); T.truthy(s.tracked.inner_fire)
  s = FB.State.New(FB.Data, env({ known={[588]=true}, settings={ show={ inner_fire=false }, sound={ inner_fire=false } } })); s:ComputeTracked(); T.falsy(s.tracked.inner_fire)
end)
T.test("Visibility override else global", function()
  local s = FB.State.New(FB.Data, env({ visibility="missing", settings={ visibility={ fortitude="expiring" } } }))
  T.eq(s:Visibility("fortitude"), "expiring"); T.eq(s:Visibility("inner_fire"), "missing")
end)
T.test("weapon oil/stone entry: class exclusions, hunter default off, off-hand weapon", function()
  local s = FB.State.New(FB.Data, env({ class="WARRIOR", instance="raid", offhandWeapon=false })); s:ComputeTracked(); T.truthy(s.tracked.weapon_mh); T.falsy(s.tracked.weapon_oh)
  s = FB.State.New(FB.Data, env({ class="WARRIOR", instance="raid", offhandWeapon=true })); s:ComputeTracked(); T.truthy(s.tracked.weapon_oh)
  s = FB.State.New(FB.Data, env({ class="SHAMAN", instance="raid" })); s:ComputeTracked(); T.falsy(s.tracked.weapon_mh)
  s = FB.State.New(FB.Data, env({ class="ROGUE", instance="raid" })); s:ComputeTracked(); T.falsy(s.tracked.weapon_mh)
  s = FB.State.New(FB.Data, env({ class="HUNTER", instance="raid" })); s:ComputeTracked(); T.falsy(s.tracked.weapon_mh)
  s = FB.State.New(FB.Data, env({ class="HUNTER", instance="raid", enabled={weapon_mh=true} })); s:ComputeTracked(); T.truthy(s.tracked.weapon_mh)
end)
T.test("flask not tracked below level 50", function()
