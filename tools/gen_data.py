"""Generate DataGen.lua from docs/superpowers/research/2026-11-08-sources-and-ranks.md.

Usage (from the addon folder):  python tools/gen_data.py

Section 1 (consumable sources) -> FB.DataGen.SOURCES[itemID]
Section 2 (rank ladders)       -> FB.DataGen.LADDERS[family] (confirmed rows only;
                                  for poisons only the learned "cast" spells)
                               -> FB.DataGen.POISON_CAST[family] = rank-1 cast spell ID
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "docs", "superpowers", "research", "2026-11-08-sources-and-ranks.md")
OUT = os.path.join(ROOT, "DataGen.lua")

POISONS = {"Instant Poison", "Deadly Poison", "Crippling Poison", "Mind-numbing Poison", "Wound Poison"}


def cells(line):
    return [c.strip() for c in line.strip().strip("|").split("|")]


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    text = open(SRC, encoding="utf-8").read()
    sec1 = text.split("## 1.")[1].split("## 2.")[0]
    sec2 = text.split("## 2.")[1].split("## Notes")[0]

    sources = []
    for line in sec1.splitlines():
        if not re.match(r"^\|\s*\d+\s*\|", line):
            continue
        c = cells(line)
        item_id, name, _rlvl, _list, kind, prof, _whb, _spell, reagents, note, conf = c[:11]
        entry = {"itemID": int(item_id), "kind": kind, "confidence": conf, "note": note}
        m = re.match(r"^(Alchemy|Cooking|Blacksmithing|Enchanting|First Aid|Engineering)\s+(\d+|\?)", prof)
        if m:
            entry["profession"] = m.group(1)
            if m.group(2) != "?":
                entry["skill"] = int(m.group(2))
        regs = []
        for part in reagents.split(","):
            mm = re.match(r"^\s*(\d+)\s*x(\d+)\s+(.+?)\s*$", part)
            if mm:
                regs.append((int(mm.group(1)), int(mm.group(2)), mm.group(3)))
        entry["reagents"] = regs
        sources.append(entry)

    ladders = {}
    poison_cast = {}
    for line in sec2.splitlines():
        if not re.match(r"^\|\s*[A-Z]", line) or line.startswith("| family"):
            continue
        c = cells(line)
        family, rank, spell, _wh, _whb, level, _indata, conf, note = (c + [""] * 9)[:9]
        if conf != "confirmed":
            continue
        if family in POISONS and not note.startswith("cast"):
            continue
        lvl = re.match(r"^(\d+)", level)
        if not lvl:
            continue
        row = (int(rank), int(spell), int(lvl.group(1)))
        ladders.setdefault(family, []).append(row)
        if family in POISONS and int(rank) == 1:
            poison_cast[family] = int(spell)

    out = []
    out.append("-- GENERATED by tools/gen_data.py from docs/superpowers/research/2026-11-08-sources-and-ranks.md")
    out.append("-- Do not edit by hand; edit the research file and re-run the generator.")
    out.append("local ADDON, FB = ...")
    out.append("FB.DataGen = FB.DataGen or {}")
    out.append("local G = FB.DataGen")
    out.append("")
    out.append("G.SOURCES = {")
    for e in sorted(sources, key=lambda x: x["itemID"]):
        parts = [f'kind = {lua_str(e["kind"])}', f'confidence = {lua_str(e["confidence"])}']
        if "profession" in e:
            parts.append(f'profession = {lua_str(e["profession"])}')
        if "skill" in e:
            parts.append(f'skill = {e["skill"]}')
        if e["reagents"]:
            regs = ", ".join(f'{{ itemID = {i}, count = {n}, name = {lua_str(nm)} }}' for i, n, nm in e["reagents"])
            parts.append(f"reagents = {{ {regs} }}")
        if e["kind"] != "crafted" and e["note"] and e["note"] != "-":
            parts.append(f'note = {lua_str(e["note"])}')
        out.append(f'  [{e["itemID"]}] = {{ {", ".join(parts)} }},')
    out.append("}")
    out.append("")
    out.append("G.LADDERS = {")
    for family in sorted(ladders):
        rows = sorted(ladders[family])
        spells = ", ".join(f"{{ rank = {r}, id = {s}, level = {l} }}" for r, s, l in rows)
        out.append(f"  [{lua_str(family)}] = {{ {spells} }},")
    out.append("}")
    out.append("")
    out.append("G.POISON_CAST = {")
    for family in sorted(poison_cast):
        out.append(f"  [{lua_str(family)}] = {poison_cast[family]},")
    out.append("}")
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print(f"wrote {OUT}: {len(sources)} sources, {len(ladders)} ladders, {len(poison_cast)} poison casts")


if __name__ == "__main__":
    main()
